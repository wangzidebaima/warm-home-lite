  // 枚举某年所有月份 [{m, days, leap}]
  function enumMonth(info) {
    var leap = info & 0xf; // 闰几月
    var res = [];
    for (var m = 1; m <= 12; m++) {
      var days = (info & (0x10000 >> m)) ? 30 : 29;
      res.push({ m: m, days: days, leap: 0 });
      if (m === leap) {
        var leapDays = (info & 0x10000) ? 30 : 29;
        res.push({ m: m, days: leapDays, leap: 1 });
      }
    }
    return res;
  }

  function toCnDay(d){
    if(d===10) return '初十';
    if(d===20) return '二十';
    if(d===30) return '三十';
    var prefix = d<10?'初':(d<20?'十':'廿');
    var rest = d%10;
    return prefix + (rest===0?'':cnNum[rest]);
  }
  function toCnMonth(m){ return cnMonth[m] + '月'; }

  function solarToLunar(sy, sm, sd){
    if (sy < 1900 || sy > 2099) return null;
    var objDate = Date.UTC(sy, sm - 1, sd);
    var offset = Math.floor((objDate - START) / 86400000);
    if (offset < 0) return null;
    // 年份：offset < 该年天数即归该年（等于0也归当年）
    var idx = 0;
    for (; idx < YEAR_DAYS.length; idx++) {
      if (offset < YEAR_DAYS[idx]) break;
      offset -= YEAR_DAYS[idx];
    }
    if (idx >= YEAR_DAYS.length) return null;
    var y = 1900 + idx;
    // 月日
    var months = enumMonth(YEAR_INFOS[idx]);
    var mi = 0;
    for (; mi < months.length; mi++) {
      if (offset < months[mi].days) break;
      offset -= months[mi].days;
    }
    var mo = months[mi];
    var d = offset + 1;
    var isLeap = !!mo.leap;
    return {
      year: y, month: mo.m, day: d, isLeap: isLeap,
      monthText: (isLeap?'闰':'')+toCnMonth(mo.m),
      dayText: toCnDay(d),
      text: (isLeap?'闰':'')+toCnMonth(mo.m)+toCnDay(d),
      ganzhi: gan[(y-4)%10]+zhi[(y-4)%12],
      animal: animals[(y-4)%12]
    };
  }

  function lunarKey(sy, sm, sd){
    var l = solarToLunar(sy, sm, sd);
    return l ? (l.month<10?'0':'')+l.month+'-'+(l.day<10?'0':'')+l.day : '';
  }

